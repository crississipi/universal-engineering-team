#!/usr/bin/env python3
"""Generate/check ALL-ROLE-SKILLS.md from canonical role skill files."""

import argparse
from pathlib import Path
import re
import sys

import yaml

from validation_common import ROOT

SOURCE = ROOT / "docs/team/expected-roles.yml"
TARGET = ROOT / "ALL-ROLE-SKILLS.md"
BEGIN = "<!-- BEGIN GENERATED ROLE SKILLS -->"
END = "<!-- END GENERATED ROLE SKILLS -->"


def render(root=ROOT):
    source = root / "docs/team/expected-roles.yml"
    data = yaml.safe_load(source.read_text(encoding="utf-8"))

    if not isinstance(data, dict) or not isinstance(data.get("roles"), list):
        raise ValueError("expected-roles.yml must contain a roles list")

    roles = data["roles"]
    if not roles or any(
        not isinstance(role, str) or not re.fullmatch(r"[a-z][a-z0-9-]*", role)
        for role in roles
    ):
        raise ValueError("Expected roles must be non-empty safe role slugs")
    if len(roles) != len(set(roles)):
        raise ValueError("expected-roles.yml contains duplicate role slugs")

    sections = []
    for role in roles:
        skill_path = root / "skills" / role / "SKILL.md"
        if not skill_path.is_file():
            raise ValueError(f"Missing canonical skill for role '{role}': {skill_path}")

        content = skill_path.read_text(encoding="utf-8").strip()
        frontmatter = re.match(r"^---\n(.*?)\n---(?:\n|$)", content, re.DOTALL)
        if not frontmatter:
            raise ValueError(f"{skill_path.relative_to(root)} has invalid/missing frontmatter")

        metadata = yaml.safe_load(frontmatter.group(1))
        if not isinstance(metadata, dict) or metadata.get("name") != role:
            raise ValueError(
                f"{skill_path.relative_to(root)} frontmatter name must be '{role}'"
            )

        title_match = re.search(r"(?m)^# (.+?)\s*$", content[frontmatter.end():])
        if not title_match:
            raise ValueError(f"{skill_path.relative_to(root)} has no top-level role heading")

        title = title_match.group(1)
        sections.append(
            f"## {title}\n\n<!-- ROLE: {role} -->\n\n{content}"
        )

    return (
        "# Consolidated Role Skills\n\n"
        "Generated from the canonical files under `skills/`. "
        "Do not edit this file directly; update the source skill and run "
        "`python scripts/build-all-role-skills.py --write`.\n\n"
        f"{BEGIN}\n\n"
        + "\n\n---\n\n".join(sections)
        + f"\n\n{END}\n"
    )


def main():
    parser = argparse.ArgumentParser(
        description="Generate or check the consolidated role skills reference."
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()

    try:
        generated = render()
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if args.write:
            TARGET.write_text(generated, encoding="utf-8")
            print("Generated ALL-ROLE-SKILLS.md from canonical role skills.")
            return 0
        if current != generated:
            print(
                "ALL-ROLE-SKILLS.md is out of sync. Run "
                "python scripts/build-all-role-skills.py --write"
            )
            return 1
        print("ALL-ROLE-SKILLS.md is synchronized with all canonical role skills.")
        return 0
    except (OSError, ValueError, yaml.YAMLError) as exc:
        print(f"ERROR: {exc}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
